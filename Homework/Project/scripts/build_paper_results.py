"""Recompute paper tables/ROC curves from frozen local predictions; CPU only.

Never edits the authored paper outline or runs model inference. Mismatch is the
positive class. Missing predictions are excluded from metrics, not counted NO.
"""
import csv
from collections import Counter, defaultdict
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import numpy as np
os.environ.setdefault('MPLCONFIGDIR', str(Path(__file__).resolve().parents[1] / 'downloads/matplotlib-cache'))
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from sklearn.metrics import (accuracy_score, balanced_accuracy_score,
    precision_recall_fscore_support, confusion_matrix, roc_auc_score,
    average_precision_score, roc_curve, precision_recall_curve)

ROOT = Path(__file__).resolve().parents[1]
PAPER = ROOT / 'paper'
TABLES = PAPER / 'tables'
FIGURES = PAPER / 'figures'
RECORDS = []
SOURCES = {}
CURVES = defaultdict(list)


def read(path):
    p = ROOT / path
    data = p.read_bytes()
    SOURCES[path.replace('\\','/')] = hashlib.sha256(data).hexdigest()
    return json.loads(data) if p.suffix == '.json' else [json.loads(l) for l in data.decode('utf-8-sig').splitlines() if l]


def tex(value):
    return str(value).translate(str.maketrans({'&': r'\&', '%': r'\%', '_': r'\_', '#': r'\#'}))


def table(name, caption, headers, rows, align=None, group_column=None):
    align = align or ('l' + 'r'*(len(headers)-1))
    body = []
    for i, row in enumerate(rows):
        if group_column is not None and i and row[group_column] != rows[i-1][group_column]:
            body.append(r'\midrule')
        body.append(' & '.join(row)+r' \\')
    content = '\n'.join(['% Generated by scripts/build_paper_results.py; do not hand-edit.',
        r'\begin{table*}[htbp]', r'\centering', r'\caption{'+caption+'}',
        r'\label{tab:'+name+'}', r'\small', r'\begin{adjustbox}{max width=\textwidth}',
        r'\begin{tabular}{'+align+'}', r'\toprule', ' & '.join(headers)+r' \\',
        r'\midrule', *body, r'\bottomrule',
        r'\end{tabular}', r'\end{adjustbox}', r'\end{table*}', ''])
    (TABLES / (name+'.tex')).write_text(content, encoding='utf-8')


def evaluate(family, model, split, truth_path, pred_path, embedded=False):
    predictions = read(pred_path)
    truth = predictions if embedded else read(truth_path)
    labels = {r['id']: r['label'] for r in truth}
    assert len(labels) == len(truth)
    selected = [r for r in predictions if r['id'] in labels]
    assert len(selected) == len(labels) and len({r['id'] for r in selected}) == len(labels)
    valid = [r for r in selected if type(r.get('prediction')) is bool]
    y = np.array([not labels[r['id']] for r in valid],dtype=bool)
    p = np.array([not r['prediction'] for r in valid],dtype=bool)
    # Preserve ranking resolution where saved logits avoid saturated probabilities.
    score_key = next((k for k in ('yes_minus_no_logit','yes_score_uncalibrated','match_score')
                      if all(k in r for r in valid)), None)
    scores = np.array([-float(r[score_key]) for r in valid]) if score_key else None
    pr,rc,f1,_ = precision_recall_fscore_support(y,p,average='binary',zero_division=0)
    _,_,macro,_ = precision_recall_fscore_support(y,p,average='macro',zero_division=0)
    _,_,matchf1,_ = precision_recall_fscore_support(~y,~p,average='binary',zero_division=0)
    cm = confusion_matrix(y,p,labels=[True,False]).tolist()
    record = dict(family=family,model=model,split=split,scored=len(valid),total=len(truth),
        accuracy=accuracy_score(y,p),balanced_accuracy=balanced_accuracy_score(y,p),
        mismatch_precision=pr,mismatch_recall=rc,mismatch_f1=f1,macro_f1=macro,match_f1=matchf1,
        confusion_matrix=cm,auroc=roc_auc_score(y,scores) if scores is not None else None,
        average_precision=average_precision_score(y,scores) if scores is not None else None,
        score_field=score_key,truth_source=truth_path or pred_path,prediction_source=pred_path)
    assert sum(map(sum,cm)) == len(valid)
    RECORDS.append(record)
    if scores is not None: CURVES[family].append((model,split,y,scores))
    return record


def figures(family):
    rows = CURVES[family]
    splits = list(dict.fromkeys(s for _,s,_,_ in rows))
    plt.rcParams.update({'font.size': 8})
    size = (3.4, 2.6) if family == 'informalization-proofnet' else (7.2,3.8)
    fig,axes = plt.subplots(2,len(splits),figsize=size,squeeze=False)
    for j,split in enumerate(splits):
        for model,s,y,score in rows:
            if s != split: continue
            fpr,tpr,_ = roc_curve(y,score)
            precision,recall,_ = precision_recall_curve(y,score)
            axes[0,j].plot(fpr,tpr,label=model,lw=1.4)
            axes[1,j].plot(recall,precision,label=model,lw=1.4)
        axes[0,j].plot([0,1],[0,1],'--',color='gray',lw=.7)
        axes[0,j].set(title=split,xlabel='False positive rate',ylabel='Mismatch recall')
        axes[1,j].set(xlabel='Mismatch recall',ylabel='Mismatch precision')
        for ax in axes[:,j]:
            ax.set_xlim(-.02,1.02); ax.set_ylim(-.02,1.02)
            ax.grid(alpha=.2); ax.legend(fontsize=7,loc='best')
    fig.tight_layout()
    fig.savefig(FIGURES/(family+'-curves.pdf'),bbox_inches='tight')
    plt.close(fig)


def classification_tables(family):
    rows = [r for r in RECORDS if r['family']==family]
    f = lambda x: '--' if x is None else f'{x:.3f}'
    table(family+'-metrics', r'Mismatch-positive classification; metrics conditional on scored pairs.',
        ['Model','Evaluation',r'$n/N$','Acc.','Bal. acc.',r'$P_-$',r'$R_-$',r'$F1_-$','Macro F1','AUROC','AP'],
        [[tex(r['model']),tex(r['split']),f"{r['scored']}/{r['total']}",
          *[f(r[k]) for k in ('accuracy','balanced_accuracy','mismatch_precision','mismatch_recall',
                            'mismatch_f1','macro_f1','auroc','average_precision')]] for r in rows],
        'llrrrrrrrrr')
    matrices = []
    for r in rows:
        (tp,fn),(fp,tn) = r['confusion_matrix']
        matrix = r'$\left[\begin{array}{rr}'+f'{tp}&{fn}'+r'\\'+f'{fp}&{tn}'+r'\end{array}\right]$'
        matrices.append([tex(r['model']),tex(r['split']),matrix,str(fn),str(fp),f(r['match_f1'])])
    table(family+'-confusion',r'Confusion matrices: rows = actual, columns = predicted; order = (mismatch, match).',
          ['Model','Evaluation','Matrix','False accepts','False rejects',r'$F1_+$'],matrices,'llcrrr')
    figures(family)


def main():
    TABLES.mkdir(parents=True,exist_ok=True); FIGURES.mkdir(parents=True,exist_ok=True)
    for model in ('untuned','first-pass','second-pass'):
        evaluate('statements','8B '+model,'Validation',
            'artifacts/two-pass/data/proofnet-validation.jsonl',f'artifacts/two-pass/{model}-validation/predictions.jsonl')
    old = 'artifacts/argument-14b/overnight-20261109'
    core = 'artifacts/argument-14b/core/test.jsonl'
    for model in ('untuned','tuned'):
        for split,truth in [('validation',old+'/budget-data/validation.jsonl'),('core',core)]:
            evaluate('random-swap','14B '+model,'Validation' if split=='validation' else 'Same theorem',truth,
                     f'{old}/{model}-{split}/predictions.jsonl')
        evaluate('masked-control','14B '+model,'Lean proof withheld',core,
                 f'{old}/{model}-core-masked/predictions.jsonl')
    for model in ('both_languages','english_only'):
        family = 'forest' if model=='both_languages' else 'english-control'
        for split in ('validation','same_theorem_diagnostic'):
            evaluate(family,'Paired RF' if model=='both_languages' else 'English-only RF',
                'Validation' if split=='validation' else 'Same theorem',None,
                f'reports/random-forest-20261110/{model}-{split}.jsonl',embedded=True)
    hard = 'artifacts/hard-related-20261110'
    for model in ('untuned-direct','tuned-direct','nl_to_lean','lean_to_nl','verbose_lean','natural_lean'):
        family = 'related-swap' if 'direct' in model else 'intermediaries'
        names = {'untuned-direct':'14B untuned','tuned-direct':'14B tuned','nl_to_lean':'English to Lean',
                 'lean_to_nl':'Lean to English','verbose_lean':'Verbose Lean','natural_lean':'Natural Lean'}
        splits = [('Validation',hard+'/data/validation.jsonl')] if 'direct' in model else []
        splits += [('Test',hard+'/data/test.jsonl'),('Same theorem',core)]
        for split,truth in splits:
            evaluate(family,names[model],split,truth,f'{hard}/{model}/predictions.jsonl')
    for split in ('validation','test'):
        evaluate('pilot32','32B untuned',split.title(),
            f'artifacts/source-balanced-20261112/data/{split}.jsonl',
            f'artifacts/source-balanced-20261112/qwen32/pretrained-{split}-predictions.json')
    # Completed ProofNet-trained informalizer: preserve raw decisions but abstain
    # on generation-limit hits, matching the recorded experimental protocol.
    pn = 'artifacts/informalization-proofnet-14b-20261113'
    generations = {r['id']: r for r in read(pn+'/generated.jsonl')}
    normalized = []
    for r in read(pn+'/judgments.jsonl'):
        truncated = generations[r['id']]['hit_generation_limit']
        normalized.append({**r, 'prediction': None if truncated else r['match'],
                           'exclusion_reason': 'generation_limit' if truncated else None})
    normalized_path = 'reports/informalization-proofnet-14b-20261113/paper-predictions.jsonl'
    (ROOT/normalized_path).write_text(''.join(json.dumps(r)+'\n' for r in normalized),encoding='utf-8')
    evaluate('informalization-proofnet','ProofNet-trained 14B','Related-swap test',
             pn+'/data/test.jsonl',normalized_path)
    # Tiny mixed-scope controls have saved decisions but no continuous scores.
    controls = read('reports/source-balanced-20261112/shortcut-controls.json')['results']
    control_rows=[]
    for name,split_results in controls.items():
        for split,result in split_results.items():
            truth=read(f'artifacts/source-balanced-20261112/data/{split}.jsonl')
            y=[not r['label'] for r in truth]; p=[not x for x in result['predictions']]
            pr,rc,f1,_=precision_recall_fscore_support(y,p,average='binary',zero_division=0)
            cm=confusion_matrix(y,p,labels=[True,False]).tolist()
            control_rows.append([tex(name),split,str(len(y)),f'{accuracy_score(y,p):.3f}',
                f'{pr:.3f}',f'{rc:.3f}',f'{f1:.3f}',tex(str(cm))])
    table('pilot-controls','Provisional source-balanced pilot: shortcut controls; no continuous scores.',
        ['Control','Split',r'$N$','Acc.',r'$P_-$',r'$R_-$',r'$F1_-$','Matrix'],control_rows,'llrrrrrl')
    for family in dict.fromkeys(r['family'] for r in RECORDS): classification_tables(family)
    compact=[]
    for r in RECORDS:
        if r['family'] not in ('statements','random-swap','forest','related-swap'): continue
        if r['family']=='related-swap' and r['split']=='Validation': continue
        label={'statements':'Statement','random-swap':'Random swap','forest':'Random swap RF','related-swap':'Related swap'}[r['family']]
        compact.append([label,tex(r['model']),tex(r['split']),f"{r['scored']}/{r['total']}",
                        *[f"{r[k]:.3f}" for k in ('accuracy','mismatch_precision','mismatch_recall','mismatch_f1','auroc')]])
    table('compact-results','Direct classification: mismatch-positive metrics; distinct protocols and evaluation sets.',
          ['Protocol','Model','Evaluation',r'$n/N$','Acc.',r'$P_-$',r'$R_-$',r'$F1_-$','AUROC'],compact,'lllrrrrrr')
    compact=[]
    for r in RECORDS:
        if r['family']=='intermediaries':
            compact.append([tex(r['model']),tex(r['split']),f"{r['scored']}/{r['total']}",
                            f"{r['accuracy']:.3f}",f"{r['mismatch_f1']:.3f}"])
    table('compact-intermediaries','Original-14B intermediaries: conditional metrics on unequal scored subsets.',
          ['Architecture','Evaluation',r'$n/N$','Acc.',r'$F1_-$'],compact,'llrrr')
    # No labels: descriptive counts, never classification metrics.
    survey=[]
    two=read('reports/two-pass/latest.json')
    for name,r in two['runs'].items():
        if name.endswith(('herald','external')):
            counts=r['predictions']
            survey.append([tex('8B '+name),str(r['rows']),str(counts.get('True',0)),str(counts.get('False',0)),str(counts.get('None',0))])
    overnight=read('reports/argument-14b-overnight/latest.json')
    for name in ('untuned-herald','tuned-herald'):
        r=overnight['runs'][name]; c=r['prediction_counts']
        survey.append([tex('14B '+name),str(r['rows']),str(c.get('True',0)),str(c.get('False',0)),str(c.get('None',0))])
    forests=read('reports/random-forest-herald-20261110/summary.json')
    for key,name in [('forest_both_languages','Paired RF Herald'),('forest_english_only','English-only RF Herald (control)')]:
        r=forests['models'][key]; excluded=forests['excluded_to_match_qwen_context_limit']
        survey.append([name,str(forests['rows']+excluded),str(r['yes']),str(r['no']),str(excluded)])
    table('unlabeled','Unlabeled surveys: decisions only; no accuracy, F1 or ROC ground truth.',
          ['Model / corpus',r'$N$','YES','NO','Unscored'],survey,'lrrrr')
    results=read('reports/hard-related-20261110/latest.json')
    comp=results['results']['compilation']['compilation']['by_target']
    table('compilation','Unique generated code: compiler outcomes; source fidelity unestablished.',
        ['Target','Compiled','Failed','Unchecked','Timeout','Import rejected','Extension rejected'],
        [[tex(k),*[str(v.get(s,0)) for s in ('compiled','compile_failed','not_checked','timeout','rejected_import','rejected_executable_extension')]]
         for k,v in comp.items() if k!='english'],'lrrrrrr')
    table('compiled-pairs','Comparisons with every generated code branch compiled.',
        ['Architecture','Test','Same-theorem diagnostic'],
        [[tex(k),'0/54','0/16'] for k in ('English to Lean','Verbose Lean','Natural Lean')],'lrr')
    related=read('reports/relatedness-20261110/summary.json')
    table('related-mining','Heuristic relatedness: original-split candidate mining.',
        ['Split','Source pairs','Candidate rows','Mean random similarity','Mean mined similarity'],
        [[tex(k),str(v['sources']),str(v['candidate_rows']),f"{v['mean_random_relatedness']:.3f}",
          f"{v['mean_mined_relatedness']:.3f}"] for k,v in related['mining']['splits'].items()],'lrrrr')
    candidates=[]
    names={'related_english_bundle_candidate':'Related English bundle',
           'related_swap_candidate':'Related proof only','source_positive_control':'Original source pair'}
    for model,groups in related['models'].items():
        for group,v in groups.items():
            if group in names:
                candidates.append([tex(model),names[group],str(v['rows']),str(v['yes_count']),str(v['rows']-v['yes_count'])])
    table('related-candidates','Unlabeled candidate survey: original random-swap models; no accuracy labels.',
          ['Model','Candidate type','Pairs','YES','NO'],candidates,'llrrr')
    # Post-hoc simple controls: reconstruct integer matrices from exact supports/recall.
    c1=read('reports/audit-20261109/statement-controls.json')['context_rule']['report']
    c2=read('reports/argument-14b-overnight/english-only-control.json')['validation']
    simple=[]
    for name,report in [('8B context-marker control',c1),('English statement/proof cosine',c2)]:
        neg,pos=report['mismatch'],report['match']
        tp=round(neg['recall']*neg['support']);tn=round(pos['recall']*pos['support'])
        cm=[[tp,int(neg['support'])-tp],[int(pos['support'])-tn,tn]]
        simple.append([name,str(int(neg['support']+pos['support'])),f"{report['accuracy']:.3f}",
            *[f"{neg[k]:.3f}" for k in ('precision','recall','f1-score')],tex(str(cm))])
    table('simple-controls','Post-hoc shortcut diagnostics; not paired semantic performance.',
          ['Control',r'$N$','Acc.',r'$P_-$',r'$R_-$',r'$F1_-$','Matrix'],simple,'lrrrrrl')
    zero=ROOT/'artifacts/zero-shot/20261106T210906480486Z/summary.csv'
    with zero.open() as f: counts=Counter(r['prediction'] for r in csv.DictReader(f))
    SOURCES[str(zero.relative_to(ROOT)).replace('\\','/')]=hashlib.sha256(zero.read_bytes()).hexdigest()
    table('initial-survey','Initial unlabeled Herald sample.', ['Pairs','YES','NO','Accuracy'],
          [[str(sum(counts.values())),str(counts['YES']),str(counts['NO']),'N/A']],'rrrr')
    manifest={'generated_utc':datetime.now(timezone.utc).isoformat(),
        'positive_class':'mismatch','matrix_order':['mismatch','match'],
        'score_policy':'Negative YES-minus-NO logit if available, otherwise negative saved match score; no threshold fitting.',
        'zero_division':0,'sources':SOURCES,'results':RECORDS}
    (PAPER/'results-snapshot.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
    fields=[k for k in RECORDS[0] if k!='confusion_matrix']+['TP','FN','FP','TN']
    with (PAPER/'results.csv').open('w',newline='',encoding='utf-8') as f:
        writer=csv.DictWriter(f,fieldnames=fields);writer.writeheader()
        for r in RECORDS:
            cm=r['confusion_matrix']; row={k:v for k,v in r.items() if k!='confusion_matrix'}
            row.update(TP=cm[0][0],FN=cm[0][1],FP=cm[1][0],TN=cm[1][1]);writer.writerow(row)
    print(f'Generated {len(RECORDS)} classification rows and {len(CURVES)} ROC/PR figures.')


if __name__=='__main__':main()
